function U {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Text
    )

    return [regex]::Unescape($Text)
}

function New-MarkdownCell {
    param(
        [string[]]$Lines
    )

    return [pscustomobject]@{
        cell_type = 'markdown'
        id = [guid]::NewGuid().ToString()
        metadata = [ordered]@{}
        source = $Lines
    }
}

function New-CodeCell {
    param(
        [string[]]$Lines
    )

    return [pscustomobject]@{
        cell_type = 'code'
        execution_count = $null
        id = [guid]::NewGuid().ToString()
        metadata = [ordered]@{}
        outputs = @()
        source = $Lines
    }
}

